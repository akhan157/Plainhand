const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { startServer } = require('../src/lifecycle.cjs');
const { exportFile, importFile, request } = require('../src/transfer.cjs');
const runtime = path.resolve(__dirname, '../build/runtime');
test('real desktop subprocess export/import backs up data, resets approvals and keeps credentials local', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ph-desktop-transfer-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const credentials = path.join(root, 'data/plainhand/secret.key'); await fs.mkdir(path.dirname(credentials), { recursive: true });
  await fs.writeFile(credentials, 'test-only-existing-machine-secret');
  const service = startServer({ executable: process.execPath, entry: path.resolve(__dirname, '../src/server-child.mjs'), cwd: runtime, env: { ...process.env, PLAINHAND_RUNTIME: runtime, PLAINHAND_WORKSPACE: root } });
  t.after(() => service.stop());
  const connection = await service.ready;
  await request(connection, 'state');
  const filename = path.join(root, 'transfer.json'); await exportFile(connection, filename);
  const data = JSON.parse(await fs.readFile(filename, 'utf8'));
  assert.equal(data.secret, undefined); assert.equal(JSON.stringify(data).includes('test-only-existing-machine-secret'), false);
  data.jobs = [{ id: 'test-job', company: 'Example', title: 'Engineer', approvedHash: 'old-hash', browserCheckpoint: { secret: true }, packet: { resume: [] }, stage: 'approved' }];
  data.secret = 'must-not-import'; data.tasks = [{ id: 'old-task', status: 'running' }];
  await fs.writeFile(filename, JSON.stringify(data));
  const result = await importFile(connection, filename, async summary => { assert.equal(summary.approvalsReset, 1); return true; });
  assert.equal(result.approvalsReset, 1);
  const state = await request(connection, 'state');
  assert.equal(state.jobs[0].approvedHash, null); assert.equal(state.jobs[0].browserCheckpoint, undefined); assert.equal(state.jobs[0].stage, 'needs-refresh');
  assert.equal(state.tasks[0].status, 'interrupted'); assert.equal(state.secret, undefined);
  assert.ok((await fs.readdir(path.join(root, 'data/plainhand/backups'))).some(name => name.endsWith('import-workspace.json')));
  assert.equal(await fs.readFile(credentials, 'utf8'), 'test-only-existing-machine-secret');
  await service.stop(); await assert.rejects(fs.access(path.join(root, 'data/plainhand/local-api.json')));
});
