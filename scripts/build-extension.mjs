#!/usr/bin/env node
// Copies the shared form helpers into the browser extension, with no bundler.
//
// The extension's content script is a classic script (chrome.scripting injects
// files, not modules), so each helper module is wrapped in a function scope, its
// relative imports are resolved to the modules already wrapped above it, and its
// exports are returned. The source files are not changed: only `import`/`export`
// keywords are rewritten in the copy.
//
//   node scripts/build-extension.mjs          write extension/vendor/plainhand-vendor.js
//   node scripts/build-extension.mjs --check  exit 1 if the copy is out of date
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const VENDOR_FILE = path.join(ROOT, 'extension/vendor/plainhand-vendor.js');

// Dependencies first: a module may import only modules listed above it.
const MODULES = [
  'plainhand/field-policy.mjs',
  'plainhand/adapters/upstream/option-match.mjs',
  'plainhand/adapters/upstream/resume-label.mjs',
  'plainhand/adapters/upstream/submit-guard.mjs',
  'plainhand/adapters/upstream/drive-action.mjs',
  'plainhand/adapters/upstream/extract.mjs',
];
// What the content script uses.
const EXPOSE = ['isSensitiveLabel', 'pickComboboxOption', 'isResumeLabel', 'isSubmitControl', 'factsOf', 'extractForm'];

function wrap(file, source) {
  const exported = [];
  let body = source.replace(/^import\s*\{([^}]*)\}\s*from\s*["']([^"']+)["'];?\s*$/gm, (_, names, from) => {
    const target = path.posix.join(path.posix.dirname(file), from);
    if (!MODULES.includes(target)) throw new Error(`${file} imports ${from}, which is not vendored.`);
    return `const {${names}} = __modules[${JSON.stringify(target)}];`;
  });
  if (/^\s*import\s/m.test(body)) throw new Error(`${file} has an import form the copy script does not handle.`);
  body = body.replace(/^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => { exported.push(name); return `${kind} ${name}`; });
  if (/^\s*export\s/m.test(body)) throw new Error(`${file} has an export form the copy script does not handle.`);
  return { exported, text: `// ---- ${file}\n__modules[${JSON.stringify(file)}] = (() => {\n${body}\nreturn { ${exported.join(', ')} };\n})();\n` };
}

export async function buildVendor() {
  const parts = [], owners = new Map();
  for (const file of MODULES) {
    const { text, exported } = wrap(file, await readFile(path.join(ROOT, file), 'utf8'));
    parts.push(text);
    for (const name of exported) owners.set(name, file);
  }
  const pick = EXPOSE.map(name => {
    const owner = owners.get(name);
    if (!owner) throw new Error(`No vendored module exports ${name}.`);
    return `  ${name}: __modules[${JSON.stringify(owner)}].${name},`;
  });
  return `// Generated by scripts/build-extension.mjs from the Plainhand sources listed below.
// Do not edit: change the source and run \`node scripts/build-extension.mjs\`.
// Upstream helpers are MIT licensed (plainhand/adapters/upstream/LICENSE).
(() => {
"use strict";
if (globalThis.__plainhandVendor) return;
const __modules = {};
${parts.join('\n')}
globalThis.__plainhandVendor = Object.freeze({
${pick.join('\n')}
});
})();
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = await buildVendor();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = await readFile(VENDOR_FILE, 'utf8'); } catch {}
    if (current !== output) { console.error('extension/vendor/plainhand-vendor.js is out of date. Run: node scripts/build-extension.mjs'); process.exit(1); }
    console.log('Extension vendor copy is up to date.');
  } else {
    await mkdir(path.dirname(VENDOR_FILE), { recursive: true });
    await writeFile(VENDOR_FILE, output);
    console.log(`Wrote ${path.relative(ROOT, VENDOR_FILE)}`);
  }
}
